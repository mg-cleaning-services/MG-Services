-- ============================================================================
-- Harden public (anonymous) requests
-- ============================================================================
--
-- Anonymous visitors can insert into public.requests through the website form.
-- The form never sends internal fields, but the REST API accepts any column,
-- so a visitor could send a fake quoted price, a schedule, a custom
-- request_code or huge text values directly.
--
-- 1. A BEFORE INSERT trigger resets every internal field for non-admin
--    inserts. Admin behaviour does not change.
-- 2. CHECK constraints limit text and array sizes for everyone.
--
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Sanitize non-admin inserts
-- ----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.sanitize_public_request()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SET search_path TO ''
  AS $function$
begin
  -- Admins (and backend roles) keep full control.
  if current_user in ('postgres', 'service_role', 'supabase_admin')
     or public.is_admin() then
    return new;
  end if;

  -- Identity and lifecycle are always decided by the database.
  new.id           := gen_random_uuid();
  new.request_code := null;  -- generated by set_request_code
  new.source       := 'website';
  new.status       := 'new';
  new.created_at   := now();
  new.updated_at   := now();

  -- Internal planning: set by the admin after contacting the customer.
  new.service_date := null;
  new.start_time   := null;
  new.end_time     := null;

  -- Internal estimation and the price agreed by phone.
  new.estimated_labour_hours := null;
  new.estimated_price        := null;
  new.quoted_price           := null;
  new.service_quantities     := '{}'::jsonb;

  return new;
end;
$function$;

REVOKE ALL ON FUNCTION public.sanitize_public_request() FROM PUBLIC, anon, authenticated;

-- Triggers on the same event fire in alphabetical order:
-- "sanitize_public_request" runs before "set_request_code",
-- so the request code is always generated from the sequence.
CREATE TRIGGER sanitize_public_request
  BEFORE INSERT ON public.requests
  FOR EACH ROW
  EXECUTE FUNCTION public.sanitize_public_request();


-- ----------------------------------------------------------------------------
-- 2. Size limits
-- ----------------------------------------------------------------------------
--
-- NOT VALID: enforced on every new insert/update, without re-checking
-- existing rows (so the migration cannot fail on old data).
--

ALTER TABLE public.requests
  ADD CONSTRAINT requests_text_lengths_check CHECK (
        char_length(first_name) <= 100
    AND char_length(coalesce(last_name, '')) <= 100
    AND char_length(phone) <= 30
    AND char_length(coalesce(email, '')) <= 254
    AND char_length(property_type) <= 100
    AND char_length(coalesce(floors, '')) <= 20
    AND char_length(bedrooms) <= 20
    AND char_length(bathrooms) <= 20
    AND char_length(coalesce(kitchens, '')) <= 20
    AND char_length(coalesce(balconies, '')) <= 20
    AND char_length(coalesce(laundries, '')) <= 20
    AND char_length(suburb) <= 100
    AND char_length(coalesce(postcode, '')) <= 20
    AND char_length(coalesce(pets, '')) <= 100
    AND char_length(preferred_time) <= 50
    AND char_length(coalesce(condition_level, '')) <= 50
    AND char_length(coalesce(last_professional_clean, '')) <= 50
    AND char_length(coalesce(notes, '')) <= 5000
  ) NOT VALID;

ALTER TABLE public.requests
  ADD CONSTRAINT requests_array_sizes_check CHECK (
        cardinality(selected_services) <= 50
    AND cardinality(extras) <= 50
  ) NOT VALID;
